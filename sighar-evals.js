function sgeDocHtml(rec, sigs, lhUrl) {
  sigs = sigs || {};
  const form = sgeFormOf(rec); if (!form) return '<div class="idoc sge"><p>نوع الاستمارة غير معروف</p></div>';
  const d = rec.data || {}, f = d.f || {};
  const m = x => '<span class="idc-m">' + x + '</span>';
  const head = '<img class="idc-lh" src="' + esc(lhUrl || SG_BG) + '" width="2000" height="351" alt="">';
  // بيانات رأس الاستمارة: ثلاث خانات في كل صف
  const cells = form.fields.map(([k, lbl]) => lbl + ': ' + m(esc(k === 'center' ? rec.center : k === 'teacher' ? rec.teacher : k === 'period' ? (rec.period || '') : idDigits(f[k] || ''))));
  if (!form.nodate) { cells.push('اليوم: ' + m(esc(d.dayName || ''))); cells.push('التاريخ: ' + m(d.hy ? idHDate(rec) : '')); }
  let info = '';
  for (let i = 0; i < cells.length; i += 3) info += '<tr>' + [0, 1, 2].map(j => '<td>' + (cells[i + j] || '') + '</td>').join('') + '</tr>';
  // البنود
  const scored = !!form.grades, hasG = !!form.gtitle, items = form.items, sc = d.sc || [], nt = d.nt || [];
  let body = '';
  items.forEach((it, i) => {
    let gcell = '';
    if (hasG && (i === 0 || items[i - 1].g !== it.g)) { let n = 1; while (items[i + n] && items[i + n].g === it.g) n++; gcell = '<td class="sge-g" rowspan="' + n + '">' + esc(it.g) + '</td>'; }
    body += '<tr>' + (hasG ? gcell : '<td class="idc-n">' + idDigits(i + 1) + '</td>') + '<td class="sge-t">' + esc(it.t) + '</td>' +
      (scored ? '<td>' + sgeFmt(it.m) + '</td><td class="sge-v">' + sgeFmt(sgeNum(sc[i])) + '</td>' : '') + '<td class="sge-t">' + esc(nt[i] || '') + '</td></tr>';
  });
  const total = sgeTotal(form, sc);
  const sum = scored
    ? '<tr class="sge-sum"><td colspan="2">الدرجة المستحقة</td><td>' + sgeFmt(form.max) + '</td><td class="sge-v">' + sgeFmt(total) + '</td><td>التقدير: ' + m(esc(sgeGradeOf(form, total))) + '</td></tr>'
    : '<tr class="sge-sum"><td>التقدير العام</td><td colspan="2" style="text-align:right">' + m(esc(d.overall || '')) + '</td></tr>';
  const cols = (hasG ? '<col style="width:96px">' : '<col style="width:40px">') + '<col>' + (scored ? '<col style="width:52px"><col style="width:66px">' : '') + '<col style="width:' + (scored ? '19%' : '30%') + '">';
  const thead = '<tr><th>' + (hasG ? esc(form.gtitle) : 'م') + '</th><th>بنود التقييم</th>' + (scored ? '<th>الدرجة</th><th>المستحقة</th>' : '') + '<th>ملاحظات</th></tr>';
  const recs = (form.recs || []).map((lbl, i) => (d.recs && d.recs[i]) ? '<div class="sge-box idc-avoid"><b>' + esc(lbl) + '</b><div>' + esc(d.recs[i]) + '</div></div>' : '').join('');
  const sigCol = (lbl, name, sg) => '<div>' + lbl + (name ? '<br>' + m(esc(name)) : '') + idSig(sg) + '</div>';
  return '<div class="idoc sg sge">' + head + '<div class="idc-body">' +
    '<div class="idc-title">' + esc(form.title) + '</div>' +
    '<table class="sge-info">' + info + '</table>' +
    '<table><colgroup>' + cols + '</colgroup>' + thead + body + sum + '</table>' + recs +
    '<div class="idc-foot idc-avoid">' + sigCol('اسم ' + form.who + ' والتوقيع', rec.teacher, sigs.tch) + sigCol('اسم المشرفة والتوقيع', d.supName || rec.supName, sigs.sup) +
      // استمارات قديمة حُفظت قبل إلغاء خانة المديرة: يبقى ما سُجّل فيها كما هو
      (!d.supName && (d.mgrName || sigs.mgr) ? sigCol('اسم المديرة والتوقيع', d.mgrName, sigs.mgr) : '') + '</div>' +
  '</div></div>';
}
